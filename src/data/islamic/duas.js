const TITLE_FIXES = { 'Fait Feels Weak': 'Faith Feels Weak', 'Received More Then Earned': 'Received More Than Earned' };

/** Makes text typeable on any keyboard: straight quotes, plain dashes, single spaces. */
export function normalize(s) {
  return s
    .replace(/[‘’ʼ`]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s*[—–]\s*/g, ' - ')
    .replace(/…/g, '...')
    .replace(/\s+/g, ' ')
    .trim();
}

// A line that names Allah ("Ya Rahman," alone, or "Ya Ra'uf,  Cover me…" with two spaces) starts a part.
const isHeader = (line) => /^Ya [^,]+(, ?Ya [^,]+|, [A-Z][a-z]+)?,\s*$/.test(line) || /^Ya [^,]+,\s{2,}\S/.test(line);

function parse(raw) {
  const duas = [];
  let cur = null;
  let part = null;
  const flush = () => {
    if (cur && part && part.trim()) cur.parts.push(normalize(part));
    part = null;
  };
  for (const line of raw.split('\n')) {
    const title = line.match(/^(\d+)\. (.+)$/);
    if (title) {
      flush();
      const t = normalize(title[2]);
      cur = { id: Number(title[1]), title: TITLE_FIXES[t] || t, parts: [] };
      duas.push(cur);
      continue;
    }
    if (!cur) continue;
    if (!line.trim()) { flush(); continue; } // a blank line ends a paragraph
    if (isHeader(line)) { flush(); part = line; continue; }
    part = part == null ? line : `${part} ${line}`;
  }
  flush();
  return duas;
}

export const DUAS = parse(RAW);
